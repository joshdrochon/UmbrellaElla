#!/usr/bin/env python3
"""GDD conformance: does the game hold the numbers the GDD prints? (Josh, Nov 12: the Small Blast drifted from HAZ-10.)

  docs/build/gdd-spec.json      generated by tools/build/gdd_spec.py from the GDD snapshot (never hand-edited)
  docs/build/gdd-bindings.json  hand-written: spec key -> where the game holds it
        {"COM-06.damage": {"tuning": "FAttackTuning.SmallDamage"},            struct default in a *Tuning.h
         "HAZ-10.radius": {"tuning": "FAttackTuning.MuzzleOffset.X"},         .X .Y .Z picks a vector component
         "MOVE-21.vertical_trim": {"tuning": "FMotorTuning.VerticalTrimPct", "scale": 1},   game * scale = GDD unit
         "X.y": {"const": "Source/.../File.h:kSymbol"},                       a `kSymbol = literal` in a file
         "X.y": {"playtest": {"line": "PLAYTEST_CAM07", "match": {"case": "ontime"}, "field": "reopen_root_z"}},
         optional "tol": absolute tolerance (the GDD's own +/- tolerance, when it prints one, wins)}

Lines (stable across runs, no line numbers):
  FAIL <key> GDD=<v> game=<v> <ref>      a bound value differs from the GDD and no docs/decisions.md row cites the Rule ID
  FAIL stale ... / FAIL broken ...       the spec file is not a fresh generation / a binding points at nothing
  EXCUSED <key> ...                      differs, but a decisions row cites the Rule ID (listed, not failing)
  UNMEASURED <key> ...                   bound to a playtest value no log reports yet (warning)
  WARN UNBOUND rule=<ID> n=<n> keys=...  spec values no binding covers (counted; --list prints one line each)
  MISMATCH=<n> BOUND=<n> UNBOUND=<n>     last line.  Exit 1 on any FAIL.
"""
import glob, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gdd_spec  # noqa: E402


def _read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


LIT = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?[fF]?"
STRUCT = re.compile(r"\b(?:struct|class)\s+(?:\w+_API\s+)?(F\w+)\b")
FIELD = re.compile(r"^\s*(?:float|double|int32|int|bool|FVector2D|FVector)\s+(\w+)\s*(?:=|\{)\s*(.*?)\s*;")


def lit(s):
    s = s.strip().rstrip("fF") if re.fullmatch(LIT, s.strip()) else s.strip()
    if s in ("true", "false"):
        return 1.0 if s == "true" else 0.0
    return float(s)


def parse_default(rhs):
    m = re.fullmatch(r"(?:FVector2D|FVector)\s*[({]\s*(.*?)\s*[)}]", rhs)
    if m:
        return [lit(x) for x in m.group(1).split(",")]
    m = re.fullmatch(r"[{(]?\s*(" + LIT + r"|true|false)\s*[)}]?\s*(?://.*)?", rhs)
    return lit(m.group(1)) if m else None


def tuning_defaults(root):
    out = {}
    for path in glob.glob(os.path.join(root, "Source", "**", "*Tuning.h"), recursive=True):
        st = None
        for line in _read(path).splitlines():
            m = STRUCT.search(line)
            if m and not line.strip().endswith(";"):
                st = m.group(1)
            m = FIELD.match(line)
            if m and st:
                val = parse_default(re.sub(r"\s*//.*$", "", m.group(2)))
                if val is not None:
                    out[f"{st}.{m.group(1)}"] = val
    return out


def tuning_value(defaults, ref):
    base, comp = (ref.rsplit(".", 1) if ref.rsplit(".", 1)[-1] in ("X", "Y", "Z") else (ref, None))
    v = defaults.get(base)
    if v is None:
        return None
    if comp:
        i = "XYZ".index(comp)
        return v[i] if isinstance(v, list) and i < len(v) else None
    return None if isinstance(v, list) else v


def const_value(root, ref):
    path, _, sym = ref.partition(":")
    try:
        text = _read(os.path.join(root, path))
    except OSError:
        return None
    m = re.search(r"\b" + re.escape(sym) + r"\s*(?:=|\{)\s*(" + LIT + r")", text)
    return lit(m.group(1)) if m else None


def latest_playtest(root):
    logs = sorted(glob.glob(os.path.join(root, "docs", "build", "playtest-logs", "*.log")))
    recs = []
    for path in logs:   # oldest first; playtest_value() takes the last report of a line, so the newest log wins
        for line in _read(path).splitlines():
            m = re.match(r"(PLAYTEST_\w+)\s+(.*)", line)
            if m:
                recs.append((m.group(1), dict(kv.split("=", 1) for kv in m.group(2).split() if "=" in kv)))
    return recs


def playtest_value(recs, spec):
    for name, kv in reversed(recs):
        if name == spec["line"] and all(kv.get(k) == v for k, v in spec.get("match", {}).items()) and spec["field"] in kv:
            try:
                return float(kv[spec["field"]])
            except ValueError:
                return None
    return None


def decision_rows(root):
    path = os.path.join(root, "docs", "decisions.md")
    if not os.path.exists(path):
        return []
    return [l for l in _read(path).split("\n") if l.startswith("|") and "SUPERSEDED by" not in l.split("|")[-2]]


def cited(rule, rows):
    rx = re.compile(r"(?<![\w-])" + re.escape(rule) + r"(?![\w-])")
    return next((r.split("|")[1].strip() for r in rows if rx.search(r)), None)


def fmt(v):
    return f"{v:.6g}"


def check(root=ROOT, spec_path=None, check_fresh=True):
    spec_path = spec_path or os.path.join(root, "docs", "build", "gdd-spec.json")
    spec = json.loads(_read(spec_path))["values"]
    bindings = {k: v for k, v in json.loads(_read(os.path.join(root, "docs", "build", "gdd-bindings.json"))).items()
                if not k.startswith("_")}
    lines, fails, mism, bound = [], 0, 0, 0
    if check_fresh and root == ROOT and gdd_spec.render() != _read(spec_path):
        lines.append("FAIL stale docs/build/gdd-spec.json differs from a fresh generation (run tools/build/gdd_spec.py)")
        fails += 1
    defaults, recs, rows = tuning_defaults(root), latest_playtest(root), decision_rows(root)
    for key in sorted(bindings):
        b = bindings[key]
        if key not in spec:
            lines.append(f"FAIL stale {key}: binding names a value the GDD spec no longer has"); fails += 1; continue
        gdd = spec[key]
        if "tuning" in b:
            game, ref = tuning_value(defaults, b["tuning"]), b["tuning"]
        elif "const" in b:
            game, ref = const_value(root, b["const"]), b["const"]
        elif "playtest" in b:
            game, ref = playtest_value(recs, b["playtest"]), f"playtest {b['playtest']['line']}.{b['playtest']['field']}"
            if game is None:
                lines.append(f"UNMEASURED {key} {ref}"); continue
        else:
            lines.append(f"FAIL broken {key}: binding has no tuning, const or playtest"); fails += 1; continue
        if game is None:
            lines.append(f"FAIL broken {key}: {ref} not found in the source"); fails += 1; continue
        game *= b.get("scale", 1)
        tol = gdd.get("tolerance", {})
        tol_abs = tol.get("value", 0) * (abs(gdd["value"]) / 100 if tol.get("unit") == "%" else 1) if tol else b.get("tol", 0)
        bound += 1
        if abs(game - gdd["value"]) > max(tol_abs, 1e-4 * abs(gdd["value"]), 1e-6):
            row = cited(gdd["rule"], rows)
            msg = f"{key} GDD={fmt(gdd['value'])}{gdd['unit']} game={fmt(game)} {ref}"
            if row:
                lines.append(f"EXCUSED {msg} (decisions row {row})")
            else:
                lines.append(f"FAIL {msg}"); fails += 1; mism += 1
    unbound = [k for k in spec if k not in bindings]
    by_rule = {}
    for k in unbound:
        by_rule.setdefault(spec[k]["rule"], []).append(k.split(".", 1)[1])
    for rule in sorted(by_rule):
        lines.append(f"WARN UNBOUND rule={rule} n={len(by_rule[rule])} keys={','.join(by_rule[rule])}")
    lines.append(f"MISMATCH={mism} BOUND={bound} UNBOUND={len(unbound)}")
    return lines, fails


def main(argv):
    root = ROOT
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])
    lines, fails = check(root)
    if "--list" in argv:
        for l in list(lines):
            m = re.match(r"WARN UNBOUND rule=(\S+) n=\d+ keys=(.*)", l)
            if m:
                lines.remove(l)
                lines[-1:-1] = [f"UNBOUND {m.group(1)}.{k}" for k in m.group(2).split(",")]
    print("\n".join(lines))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
